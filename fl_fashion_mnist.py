class FashionCNN(nn.Module):
  def __init__(self):
    super().__init__()
    self.conv1 = nn.Conv2d(1, 16, kernel_size=3, padding = 1)
    self.pool = nn.MaxPool2d(2,2)

    self.conv2 = nn.Conv2d(16, 32, kernel_size=3, padding=1)

    self.fc1 = nn.Linear(32 * 7 * 7, 128)
    self.fc2 = nn.Linear(128, 10)

  def forward(self, x):
    x = self.pool(F.relu(self.conv1(x)))
    x = self.pool(F.relu(self.conv2(x)))
    x = torch.flatten(x, 1)
    x = F.relu(self.fc1(x))
    x = self.fc2(x)

    return x

global_model = FashionCNN()
print(global_model)

def train_local_model(global_model, client_dataset, epochs = 1, batch_size = 64, lr = 0.001):
  local_model = copy.deepcopy(global_model).to(device)

  dataloader = DataLoader(client_dataset, batch_size = batch_size, shuffle = True)

  criterion = nn.CrossEntropyLoss()
  optimizer = torch.optim.Adam(local_model.parameters(), lr = lr)

  local_model.train()

  for epoch in range(epochs):
    train_loss = 0.0

    for images, labels in dataloader:
      images = images.to(device)
      labels = labels.to(device)

      optimizer.zero_grad()

      outputs = local_model(images)
      loss = criterion(outputs, labels)

      loss.backward()
      optimizer.step()

      train_loss += loss.item()

    avg_loss = train_loss / len(dataloader)

  return local_model.cpu().state_dict()

